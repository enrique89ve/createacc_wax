const DEFAULT_CHAR_WIDTH = 556

/**
 * Measure the width of a string in points at the given font size.
 * Uses Helvetica AFM metrics (widths are in 1/1000 of a unit).
 */
export function measureText(text: string, fontSize: number): number {
	let width = 0
	for (let i = 0; i < text.length; i++) {
		const code = text.charCodeAt(i)
		width += HELVETICA_WIDTHS[code] ?? DEFAULT_CHAR_WIDTH
	}
	return (width / 1000) * fontSize
}
